--=========================================================
-- Report: Customer Performance Report
-- Purpose:
--   Analyze customer behavior and profitability.
--
-- Analysis Dimensions:
--   - Customer
--   - Customer Segment
--
-- Source:
--   gold.fact_sales
--   gold.dim_customer
--=========================================================

USE walmart;
GO


/* =========================================================
   1. CUSTOMER PERFORMANCE REPORT
   ========================================================= */

CREATE OR ALTER VIEW Analytics.report_customer_performance
AS

SELECT
    c.Customer_ID,
    c.Customer_Name,
    c.Customer_Age,
    c.Customer_Segment,

    -- Number of unique orders
    COUNT(DISTINCT f.Order_ID) AS Total_Orders,

    -- Total quantity purchased
    SUM(f.Order_Quantity) AS Total_Quantity_Purchased,

    -- Total revenue generated by customer
    SUM(f.Sales) AS Total_Sales,

    -- Total profit generated by customer
    SUM(f.Profit) AS Total_Profit,

    -- Average order value
    CAST(
        SUM(f.Sales)
        / NULLIF(COUNT(DISTINCT f.Order_ID), 0)
        AS DECIMAL(18,2)
    ) AS Average_Order_Value

FROM gold.fact_sales f

LEFT JOIN gold.dim_customers c
    ON f.Customer_ID = c.Customer_ID

GROUP BY
    c.Customer_ID,
    c.Customer_Name,
    c.Customer_Age,
    c.Customer_Segment;
GO







